import FenpoProtocol
import Foundation

/// Something from the iPhone's clipboard to put on the PC's clipboard.
public struct ClipboardPayload: Equatable, Sendable {
    /// What was copied.
    public enum Content: Equatable, Sendable {
        /// Plain text.
        case text(String)

        /// A web link.
        case url(URL)

        /// PNG or JPEG bytes, at most `ClipboardPayload.maxImageBytes`.
        case image(Data, mimeType: String)
    }

    /// Images larger than this travel as a file transfer (protocol `ClipboardItem`).
    public static let maxImageBytes = 512 * 1024

    /// What was copied.
    public var content: Content

    /// A password or a code: the PC keeps it out of its clipboard list.
    public var isSensitive: Bool

    /// Creates a payload. Text that looks like a one-time code is always sensitive.
    /// - Parameters:
    ///   - content: What was copied.
    ///   - isSensitive: Marked as private by the app it came from.
    public init(_ content: Content, isSensitive: Bool = false) {
        self.content = content
        if case .text(let text) = content, ClipboardSensitivity.looksLikeOneTimeCode(text) {
            self.isSensitive = true
        } else {
            self.isSensitive = isSensitive
        }
    }

    /// There is nothing to send.
    public var isEmpty: Bool {
        switch content {
        case .text(let text):
            text.isEmpty
        case .url(let url):
            url.absoluteString.isEmpty
        case .image(let data, _):
            data.isEmpty
        }
    }

    /// Kind and size for logs; never the content.
    public var logDescription: String {
        let kind = switch content {
        case .text(let text):
            "text, \(text.count) characters"
        case .url:
            "link"
        case .image(let data, let mimeType):
            "image, \(mimeType), \(data.count) bytes"
        }
        return isSensitive ? "\(kind), sensitive" : kind
    }

    /// The protocol message.
    /// - Parameter id: Item id.
    public func item(id: String = UUID().uuidString) -> Fenpo_V1_ClipboardItem {
        var item = Fenpo_V1_ClipboardItem()
        item.itemID = id
        item.sensitive = isSensitive
        switch content {
        case .text(let text):
            item.text = text
        case .url(let url):
            item.url = url.absoluteString
        case .image(let data, let mimeType):
            var image = Fenpo_V1_ClipboardImage()
            image.mimeType = mimeType
            image.data = data
            item.image = image
        }
        return item
    }
}

/// Tells passwords and codes apart from ordinary clipboard content, so they stay out of clipboard
/// lists and are never sent without the user's tap.
public enum ClipboardSensitivity {
    /// Pasteboard types that password managers and other apps add to private content
    /// (nspasteboard.org conventions).
    public static let markerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// Whether the pasteboard's types mark the content as private.
    /// - Parameter types: Type identifiers on the pasteboard.
    public static func isMarked(types: [String]) -> Bool {
        types.contains { markerTypes.contains($0) }
    }

    /// Four to eight digits, optionally grouped with spaces or dashes ("482 913", "1234-5678"):
    /// most likely a one-time code.
    /// - Parameter text: Copied text.
    public static func looksLikeOneTimeCode(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard trimmed.allSatisfy({ $0.isASCII && ($0.isNumber || $0 == " " || $0 == "-") }) else {
            return false
        }
        let digits = trimmed.filter(\.isNumber)
        return (4...8).contains(digits.count)
    }
}
